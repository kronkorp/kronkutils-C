#ifndef KRONKUTILS_DYNARRAY_H
    #define KRONKUTILS_DYNARRAY_H
    #include <stddef.h>

///////////////////////////////////////////////////////////////////////////////
/**
 * @struct kronkutils_dynarray_header
 *
 * @brief  Hold essential informations for dynamic array
 */
///////////////////////////////////////////////////////////////////////////////
typedef struct kronkutils_dynarray_header {

    size_t size;  //!< The size of the vector (allocated)
    size_t load;  //!< The usage of the vector (<= size)
    size_t type;  //!< The size of the type that fill the vector (e.g: 4 for int)

} kuDynarrayHeader;
///////////////////////////////////////////////////////////////////////////////


///////////////////////////////////////////////////////////////////////////////
int __kuDynarray_init(void **ptr, size_t initialSize, size_t typesize);
#define kuDynarray_init(ptr, initialSize, type) (__kuDynarray_init((void **)ptr, initialSize, sizeof(typesize)))
///////////////////////////////////////////////////////////////////////////////


///////////////////////////////////////////////////////////////////////////////
void* __kuDynarray_at(const void *ptr, size_t idx);
#define kuDynarray_at(ptr, idx) (typeof(ptr))(__kuDynarray_at((void **)ptr))
///////////////////////////////////////////////////////////////////////////////


///////////////////////////////////////////////////////////////////////////////
void* __kuDynarray_last(const void *ptr);
#define kuDynarray_last(ptr) (typeof(ptr))(__kuDynarray_last(ptr))
///////////////////////////////////////////////////////////////////////////////


///////////////////////////////////////////////////////////////////////////////
int __kuDynarray_pushBack(void **ptr, const void *e);
#define kuDynarray_pushBack(ptr, e) (__kuDynarray_pushBack((void *)&(ptr), (void *)&(typeof(e)){ e }))
///////////////////////////////////////////////////////////////////////////////


///////////////////////////////////////////////////////////////////////////////
void __kuDynarray_popBack(void **ptr);
#define kuDynarray_popBack(ptr) (__kuDynarray_popBack((void *)&(ptr)))
///////////////////////////////////////////////////////////////////////////////


///////////////////////////////////////////////////////////////////////////////
void kuDynarray_clear(void *ptr);
///////////////////////////////////////////////////////////////////////////////


///////////////////////////////////////////////////////////////////////////////
void kuDynarray_free(void *ptr);
///////////////////////////////////////////////////////////////////////////////


///////////////////////////////////////////////////////////////////////////////
size_t kuDynarray_getSize(const void *ptr);
///////////////////////////////////////////////////////////////////////////////


///////////////////////////////////////////////////////////////////////////////
size_t kuDynarray_getLoad(const void *ptr);
///////////////////////////////////////////////////////////////////////////////


///////////////////////////////////////////////////////////////////////////////
size_t kuDynarray_getTypeSize(const void *ptr);
///////////////////////////////////////////////////////////////////////////////


///////////////////////////////////////////////////////////////////////////////
kuDynarrayHeader* kuDynarray_getHeader(const void *ptr);
///////////////////////////////////////////////////////////////////////////////

#endif /* KRONKUTILS_DYNARRAY_H */
